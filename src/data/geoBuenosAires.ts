export const GEO_PROVINCIAS = Object.keys(GEO_BA);

export function geoComunas(provincias: string[]): string[] {
  const src = provincias.length ? provincias : GEO_PROVINCIAS;
  return Array.from(new Set(src.flatMap((p) => Object.keys(GEO_BA[p] ?? {})))).sort();
}

export function geoBarrios(provincias: string[], comunas: string[]): string[] {
  const src = provincias.length ? provincias : GEO_PROVINCIAS;
  const out = new Set<string>();
  src.forEach((p) => {
    Object.entries(GEO_BA[p] ?? {}).forEach(([c, barrios]) => {
      if (comunas.length === 0 || comunas.includes(c)) barrios.forEach((b) => out.add(b));
    });
  });
  return Array.from(out).sort();
}
